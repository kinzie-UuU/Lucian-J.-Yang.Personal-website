const clientNames = ["顾家家居", "追觅科技", "信维通信", "顺丰", "本来生活", "碳小熊", "糯上有点", "功能粥", "吉利", "中兴", "鞍钢", "爱情地产", "安吉尔", "固德威", "心中甜", "瓷和居", "熙图", "85°C"];

const getCleanLang = () => document.documentElement.lang === "en" ? "en" : "zh";

const applyCleanCopy = () => {
  const lang = getCleanLang();
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = cleanCopy[lang][node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll('.lang-button[data-lang="zh"]').forEach((button) => {
    button.textContent = "中";
  });
  document.querySelectorAll(".contact-copy-label").forEach((node) => {
    if (node.textContent.trim() !== "WeChat") node.textContent = lang === "zh" ? "邮箱" : "Email";
  });
  document.querySelectorAll(".contact-copy-hint").forEach((node) => {
    node.textContent = lang === "zh" ? "点击复制" : "Click to copy";
  });
  const toast = document.querySelector("#contact-toast");
  if (toast) toast.textContent = lang === "zh" ? "已复制" : "Copied";
  document.querySelectorAll(".clients-track").forEach((track) => {
    track.querySelectorAll("span").forEach((span, index) => {
      span.textContent = clientNames[index % clientNames.length];
    });
  });
};

const applyCleanFocus = (workKey) => {
  const lang = getCleanLang();
  const data = cleanWorks[workKey];
  if (!data) return;
  const kicker = document.querySelector("#hero-focus-kicker");
  const title = document.querySelector("#hero-focus-title");
  const desc = document.querySelector("#hero-focus-desc");
  const focus = document.querySelector("#hero-focus-meta-a");
  const value = document.querySelector("#hero-focus-meta-b");
  const enter = document.querySelector("#hero-focus-enter");
  if (kicker) kicker.textContent = lang === "zh" ? "当前项目" : "Active Project";
  if (title) title.textContent = data.title[lang];
  if (desc) desc.textContent = data.description[lang];
  if (focus) focus.textContent = data.focus[lang];
  if (value) value.textContent = data.value[lang];
  if (enter) enter.textContent = cleanCopy[lang].hero_action_works;
};

document.querySelectorAll(".lang-button").forEach((button) => {
  button.addEventListener("click", () => {
    window.setTimeout(() => {
      applyCleanCopy();
      const activeCard = document.querySelector(".hero-card.is-active") || document.querySelector(".hero-card");
      applyCleanFocus(activeCard?.dataset.work || "oem");
    }, 0);
  });
});

document.querySelectorAll(".hero-card").forEach((card) => {
  ["pointerenter", "focus", "click"].forEach((eventName) => {
    card.addEventListener(eventName, () => {
      window.setTimeout(() => applyCleanFocus(card.dataset.work), 0);
    });
  });
});

applyCleanCopy();
applyCleanFocus("oem");
